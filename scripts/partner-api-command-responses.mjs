import { uuid } from './partner-api-input-schemas.mjs';
const string={type:'string'},boolean={type:'boolean'},cents={type:'integer',minimum:0,maximum:Number.MAX_SAFE_INTEGER},time={type:'string',format:'date-time'},date={type:'string',format:'date'},hash={type:'string',pattern:'^[a-f0-9]{64}$'};
const nullable=schema=>({anyOf:[schema,{type:'null'}]});
const ref=name=>({$ref:'#/components/schemas/'+name});
const object=(properties,optional=[])=>({type:'object',properties,required:Object.keys(properties).filter(k=>!optional.includes(k)),additionalProperties:false});

export function commandResponseSchemas(){
 const schemas={},define=(action,properties,optional=[])=>{schemas['CommandResult_'+action.replaceAll('.','_')]=object(properties,optional);};
 const revision={id:uuid,revision:cents},status={...revision,status:string};
 define('program.create',revision);
 define('program.configure',{...revision,enabled:boolean,weeklyCapCents:cents});
 define('program.week_cap',{...revision,capCents:cents,committedCents:cents,remainingCents:cents});
 define('partner.create',{...status,displayName:string});
 define('partner.invite',{token:{type:'string',pattern:'^[A-Za-z0-9_-]{43}$',description:'One-time private handoff secret. Never log, cache publicly or embed in a URL.'},partnerId:uuid,purpose:{type:'string',enum:['enroll','recover']},expiresAt:time});
 define('partner.revoke',{ok:{type:'boolean',const:true}});
 define('campaign.create',{...status,terms:ref('OfferSnapshot')});
 for(const action of ['publish','pause'])define('campaign.'+action,status);
 define('gig.offer',{...status,terms:ref('OfferSnapshot')});
 define('gig.accept',{...status,agreementIssueId:uuid,feeCents:cents,maximumBonusCents:cents,authorizationWeek:date,referral:nullable(object({id:uuid,code:string,policyHash:hash}))});
 define('gig.counteroffer',{...status,negotiationId:uuid});
 define('gig.reoffer',{...status,terms:ref('OfferSnapshot')});
 for(const action of ['decline','submit','request_cancel','report_unsafe','dispute','withdraw','approve','request_changes','make_payable'])define('gig.'+action,{...status,feeCents:cents});
 define('gig.reconcile',{...status,payableId:uuid,amountDueCents:cents});
 define('material.record',{id:uuid,eventType:{type:'string',enum:['issued','returned']},items:{type:'array',minItems:1,maxItems:50,items:object({label:string,count:{type:'integer',minimum:1,maximum:10000}})}});
 define('visit.record',{id:uuid,leadId:nullable(uuid),status:{type:'string',const:'recorded'}});
 define('lead.review',{...status,qualificationId:nullable(uuid)});
 for(const action of ['withdraw','delete','correct'])define('lead.'+action,revision);
 for(const action of ['start','pause','resume','stop'])schemas['CommandResult_activity_'+action]={$ref:'#/components/schemas/ActivityResponse/properties/items/items'};
 define('activity.delete',{id:uuid,deleted:{type:'boolean',const:true}});
 define('profile.update',revision);
 define('profile.export',{batchId:uuid,filename:string,generatedAt:time,expiresAt:time,sha256:hash,downloadPath:string});
 schemas.CommandResult_statement_export=ref('StatementExportResponse');
 define('statement.schedule',{programId:uuid,revision:cents,enabled:boolean,firstDueWeek:nullable(date)});
 schemas.CommandResult_finance_export=ref('AccountingDownload');
 for(const action of ['record','reverse'])define('payment.'+action,{id:uuid,payableId:uuid,paidCents:cents,outstandingCents:cents});
 define('payable.adjust',{id:uuid,payable:ref('Payable')});
 define('referral.attribute',{id:uuid,referralId:uuid,status:{type:'string',const:'attributed_not_paid'}});
 define('referral.verify_sale',{id:uuid,referralId:uuid,status:{type:'string',const:'verified_not_awarded'}});
 define('referral.award',{id:uuid,payableId:uuid,amountCents:cents});
 define('legal.seed_templates',{created:cents});
 define('legal.save',{documentId:uuid,versionId:uuid,revision:cents,versionNo:cents,hash,status:{type:'string',const:'draft'}});
 define('legal.request_review',status);
 define('legal.record_review',{id:uuid,versionId:uuid,hash,scope:string,decision:string});
 for(const action of ['add_comment','resolve_comment'])define('legal.'+action,{id:uuid});
 define('legal.publish',{...status,versionId:uuid,hash});
 define('legal.retire',revision);
 define('legal.issue',{id:uuid,versionId:uuid,snapshotHash:hash,markdown:string},['markdown']);
 define('agreement.acknowledge',{id:uuid,issueId:uuid,snapshotHash:hash,readAcknowledged:{type:'boolean',const:true}});
 define('legal.export_package',{id:uuid,sha256:hash,filename:string,expiresAt:time,versionCount:cents,publicKeyFingerprint:hash,downloadPath:string});
 define('legal.import_feedback',{id:uuid,packageId:uuid,versionId:uuid,sha256:hash,manualReviewRequired:{type:'boolean',const:true},commentCount:cents,changeCount:cents});
 return schemas;
}
