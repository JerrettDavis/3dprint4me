"""Import user-supplied reference, retaining exact main-shell coordinates.

Development only: Python + trimesh. Usage:
  python scripts/import-pumpkin-reference.py path/to/PumpkinHappyEyesstl.stl
Runtime uses only the existing fflate dependency; no external resource loads.
"""
import base64
import gzip
import hashlib
import json
from pathlib import Path
import struct
import sys

import trimesh
import numpy as np

source = Path(sys.argv[1])
raw = source.read_bytes()
original = trimesh.load(source, force="mesh")
shell = max(original.split(only_watertight=False), key=lambda c: len(c.faces))
assert shell.is_watertight and shell.is_winding_consistent
assert (shell.bounds == original.bounds).all(), "Removing debris must not change bounds"
vertices = shell.vertices.astype("<f4").tobytes()
indices = shell.faces.astype("<u4").tobytes()
payload = struct.pack("<II", len(shell.vertices), len(shell.faces)) + vertices + indices
data = base64.b64encode(gzip.compress(payload, mtime=0)).decode("ascii")
metadata = {
    "source": source.name,
    "sourceSha256": hashlib.sha256(raw).hexdigest(),
    "meshSha256": hashlib.sha256(payload).hexdigest(),
    "vertices": len(shell.vertices),
    "triangles": len(shell.faces),
    "bounds": shell.bounds.tolist(),
    "minZ": float(shell.bounds[0, 2]),
    "socketDiameter": 4,
    "removedDebrisTriangles": len(original.faces) - len(shell.faces),
}
out = Path(__file__).resolve().parents[1] / "customizer/generators/pumpkin/reference-data.js"
out.write_text(
    "// Generated by scripts/import-pumpkin-reference.py from the user-supplied STL.\n"
    "// Exact float32 coordinates; only disconnected microscopic debris removed.\n"
    f"export const REFERENCE = Object.freeze({json.dumps(metadata, separators=(',', ':'))});\n"
    f"export const DATA = '{data}';\n", encoding="utf-8"
)
# Close the actual upward-facing outer roof downward to form a cutting envelope.
# The bore is filled at runtime. Keep the original roof vertices unchanged.
mask = (shell.triangles[:, :, 2].min(axis=1) > 10) & (shell.face_normals[:, 2] > 0.1)
patch = shell.submesh([mask], append=True)
n = len(patch.vertices)
lower = patch.vertices.copy()
lower[:, 2] = 0
edges = patch.edges[trimesh.grouping.group_rows(patch.edges_sorted, require_count=1)]
walls = np.array([[a, b+n, b] for a, b in edges] + [[a, a+n, b+n] for a, b in edges])
crown = trimesh.Trimesh(vertices=np.vstack([patch.vertices, lower]),
    faces=np.vstack([patch.faces, patch.faces[:, ::-1]+n, walls]), process=False)
assert crown.is_watertight and crown.is_winding_consistent
crown_payload = struct.pack('<II', len(crown.vertices), len(crown.faces)) + crown.vertices.astype('<f4').tobytes() + crown.faces.astype('<u4').tobytes()
crown_data = base64.b64encode(gzip.compress(crown_payload, mtime=0)).decode('ascii')
with out.open('a', encoding='utf-8') as f:
    f.write(f"export const CROWN_DATA = '{crown_data}';\n")
print(json.dumps(metadata, indent=2))
