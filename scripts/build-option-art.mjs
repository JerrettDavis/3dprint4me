// Reproducible 2D choice illustrations from the exact pumpkin face geometry.
import { writeFile } from 'node:fs/promises';
import { loadEngine } from '../customizer/framework/engine.js';
import { FACE_PRESETS, buildFace } from '../customizer/generators/pumpkin/faces.js';
import pumpkin from '../public/assets/js/customize/generators/pumpkin.js';
const { CrossSection } = await loadEngine();
const paths = {};
for (const [id, spec] of Object.entries(FACE_PRESETS)) {
  const temps = [];
  const result = buildFace(CrossSection, spec, 80, value => { temps.push(value); return value; });
  const serialize = section => section?.toPolygons().map(points => points.map(([x,y], i) => `${i ? 'L' : 'M'}${(60+x).toFixed(2)},${(40-y).toFixed(2)}`).join('')+'Z').join('') ?? '';
  paths[id] = { main: serialize(result.main), accent: serialize(result.accent) };
  for (const value of new Set(temps.reverse())) value.delete();
}
const features = {};
for (const key of ['eye_shape','nose_shape','mouth_shape']) {
  features[key] = {};
  for (const option of pumpkin.schema[key].options) {
    const temps=[];
    const result=buildFace(CrossSection,{...FACE_PRESETS.cute,[key.split('_')[0]]:option.value},80,value=>{temps.push(value);return value;});
    const serialize=section=>section?.toPolygons().map(points=>points.map(([x,y],i)=>`${i?'L':'M'}${(60+x).toFixed(2)},${(40-y).toFixed(2)}`).join('')+'Z').join('')??'';
    features[key][option.value]={main:serialize(result.main),accent:serialize(result.accent)};
    for(const value of new Set(temps.reverse()))value.delete();
  }
}
await writeFile(new URL('../customizer/framework/face-art.js', import.meta.url), `// Generated by scripts/build-option-art.mjs from the actual builder's face polygons.\nexport const FACE_ART = ${JSON.stringify(paths)};\nexport const FACE_FEATURE_ART = ${JSON.stringify(features)};\n`);
console.log(`Generated ${Object.keys(paths).length} geometry-derived face illustrations.`);
