// Local CLI slicer adapter (PrusaSlicer-compatible command line by default). The model
// is written to a private temporary directory, the binary runs without a shell and
// with a hard timeout, and only the G-code summary comments are parsed.
import { execFile } from "node:child_process";
import { mkdtemp, open, rm, stat, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { extname, join } from "node:path";

import { SliceError } from "../slicer-contract.js";

const DEFAULT_ARGS = ["--export-gcode", "--load", "{profile}", "--output", "{output}", "{model}"];
const SUMMARY_BYTES = 256 * 1024;

function run(file, args, { timeoutMs, cwd }) {
  return new Promise((resolve, reject) => {
    execFile(file, args, { timeout: timeoutMs, killSignal: "SIGKILL", maxBuffer: 1024 * 1024, cwd, windowsHide: true, shell: false }, (error, stdout, stderr) => {
      if (error) reject(Object.assign(error, { stdout, stderr }));
      else resolve({ stdout, stderr });
    });
  });
}

/** Parses "1d 2h 3m 4s" style durations used by PrusaSlicer/OrcaSlicer summaries. */
export function parseDuration(value) {
  const match = String(value).trim().match(/^(?:(\d+)d\s*)?(?:(\d+)h\s*)?(?:(\d+)m\s*)?(?:(\d+(?:\.\d+)?)s)?$/);
  if (!match || !match.slice(1).some(Boolean)) return null;
  const [, d = 0, h = 0, m = 0, s = 0] = match;
  return Number(d) * 86400 + Number(h) * 3600 + Number(m) * 60 + Number(s);
}

/** Reads summary comments from G-code text (header and footer). */
export function parseGcodeSummary(source) {
  const pick = pattern => { const match = source.match(pattern); return match ? match[1].trim() : null; };
  const sum = value => value == null ? null : value.split(",").map(Number).filter(Number.isFinite).reduce((total, item) => total + item, 0);
  const elapsedSeconds = parseDuration(pick(/^;\s*estimated printing time(?: \(normal mode\))?\s*[=:]\s*(.+)$/im) ?? pick(/^;\s*model printing time:\s*([^;]+?)(?:;|$)/im) ?? "");
  const grams = pick(/^;\s*total filament used \[g\]\s*=\s*(.+)$/im) ?? pick(/^;\s*filament used \[g\]\s*=\s*(.+)$/im);
  return {
    elapsedSeconds,
    materialGrams: sum(grams),
    materialMm: sum(pick(/^;\s*filament used \[mm\]\s*=\s*(.+)$/im)),
    purgeGrams: sum(pick(/^;\s*(?:total\s+)?(?:flush|purge|wipe tower)[^=\n]*\[g\]\s*=\s*(.+)$/im)),
    supportGrams: sum(pick(/^;\s*support[^=\n]*\[g\]\s*=\s*(.+)$/im)),
    toolChanges: Number(pick(/^;\s*total toolchanges\s*=\s*(\d+)$/im) ?? pick(/^;\s*total filament change:\s*(\d+)/im)) || 0,
    layerCount: Number(pick(/^;\s*total layers? (?:count|number)\s*[=:]\s*(\d+)$/im)) || null,
    version: pick(/^;\s*generated by\s+(.+?)\s+on\b/im)
  };
}

async function readSummary(path) {
  const handle = await open(path, "r");
  try {
    const { size } = await handle.stat();
    const headLength = Math.min(size, 64 * 1024);
    const tailLength = Math.min(size, SUMMARY_BYTES);
    const head = Buffer.alloc(headLength);
    const tail = Buffer.alloc(tailLength);
    await handle.read(head, 0, headLength, 0);
    await handle.read(tail, 0, tailLength, size - tailLength);
    return `${head.toString("utf8")}\n${tail.toString("utf8")}`;
  } finally { await handle.close(); }
}

export function createLocalCliSlicer({ bin, profilePath, args = DEFAULT_ARGS, engine = "prusaslicer-cli", engineVersion = null, timeoutMs = 120_000, profileId = null }) {
  if (!bin) throw new TypeError("SLICER_BIN is required for the local CLI slicer.");
  const scripted = [".js", ".mjs"].includes(extname(bin).toLowerCase());
  const command = scripted ? process.execPath : bin;
  const prefix = scripted ? [bin] : [];
  let cachedVersion = engineVersion;
  async function version(cwd) {
    if (cachedVersion) return cachedVersion;
    try {
      const { stdout } = await run(command, [...prefix, "--help"], { timeoutMs: 10_000, cwd });
      cachedVersion = (stdout.match(/\b[\w-]*slicer[-\s]v?(\d+[\w.+-]*)/i)?.[1] ?? "unknown").slice(0, 80);
    } catch { cachedVersion = "unknown"; }
    return cachedVersion;
  }
  return {
    engine,
    async estimateSlice({ bytes, filename, timeoutMs: limit = timeoutMs }) {
      const directory = await mkdtemp(join(tmpdir(), "3dp-slice-"));
      try {
        const model = join(directory, `model${extname(filename).toLowerCase() === ".3mf" ? ".3mf" : ".stl"}`);
        const output = join(directory, "out.gcode");
        await writeFile(model, bytes, { mode: 0o600 });
        const template = profilePath ? args : args.filter((arg, index) => arg !== "{profile}" && !(arg === "--load" && args[index + 1] === "{profile}"));
        const resolved = template.map(arg => arg.replace("{model}", model).replace("{output}", output).replace("{profile}", profilePath ?? ""));
        try { await run(command, [...prefix, ...resolved], { timeoutMs: limit, cwd: directory }); }
        catch (error) {
          if (error.code === "ENOENT") throw new SliceError("unavailable", "The slicer binary was not found.");
          if (error.killed || error.signal === "SIGKILL") throw new SliceError("timeout", `The slicer exceeded ${limit} ms.`);
          throw new SliceError("slicer_failed", `The slicer exited with ${error.code ?? "an error"}.`);
        }
        const exists = await stat(output).then(info => info.size > 0).catch(() => false);
        if (!exists) throw new SliceError("invalid_output", "The slicer produced no G-code.");
        const summary = parseGcodeSummary(await readSummary(output));
        return {
          engine, engineVersion: summary.version?.match(/(\d+[\w.+-]*)/)?.[1] ?? await version(directory),
          profileId: profileId ?? (profilePath ? profilePath.split(/[\\/]/).pop() : "default"),
          elapsedSeconds: summary.elapsedSeconds, materialGrams: summary.materialGrams, materialMm: summary.materialMm,
          purgeGrams: summary.purgeGrams, supportGrams: summary.supportGrams, toolChanges: summary.toolChanges, layerCount: summary.layerCount, warnings: []
        };
      } finally { await rm(directory, { recursive: true, force: true }); }
    }
  };
}
